import { mkdir, rm } from "node:fs/promises";
import { join } from "node:path";

// The launcher imports the TypeScript module's command-prefix validator as code.
// Embed a distinct bundle so Bun never resolves that same path as a file asset.
const output = "src/harnesses/pi/resources/extensions/terminal-permissions.mjs";
const temporary = join(
  "node_modules",
  ".cache",
  `terminal-permissions-${process.pid}-${crypto.randomUUID()}`,
);
await mkdir(temporary, { recursive: true });
try {
  const result = await Bun.build({
    entrypoints: ["src/harnesses/pi/resources/extensions/terminal-permissions.ts"],
    external: ["@earendil-works/pi-coding-agent"],
    target: "node",
    format: "esm",
    minify: true,
    outdir: temporary,
    naming: "terminal-permissions.mjs",
  });
  if (!result.success) {
    throw new Error(
      `Terminal permissions extension bundle failed:\n${result.logs.map((log) => log.message).join("\n")}`,
    );
  }
  const artifact = result.outputs[0];
  if (!artifact) throw new Error("Missing terminal permissions extension artifact");
  const expected = `// Generated by bun run terminal:build. Do not edit.\n${await artifact.text()}`;
  if (process.argv.includes("--check")) {
    const current = await Bun.file(output)
      .text()
      .catch(() => undefined);
    if (current !== expected) {
      throw new Error("Terminal permissions bundle is stale; run bun run terminal:build");
    }
  } else {
    await Bun.write(output, expected);
  }
} finally {
  await rm(temporary, { recursive: true, force: true });
}

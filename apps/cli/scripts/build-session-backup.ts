import { mkdir, rm } from "node:fs/promises";
import { join } from "node:path";

const output = "src/harnesses/pi/resources/extensions/session-backup.mjs";
const temporary = join("node_modules", ".cache", `session-backup-${process.pid}`);
await mkdir(temporary, { recursive: true });
try {
  const result = await Bun.build({
    entrypoints: ["src/harnesses/pi/session-backup/index.ts"],
    external: ["@earendil-works/pi-coding-agent"],
    target: "node",
    format: "esm",
    minify: true,
    outdir: temporary,
    naming: "session-backup.mjs",
  });
  if (!result.success) throw new Error("Session backup extension bundle failed");
  const artifact = result.outputs[0];
  if (!artifact) throw new Error("Missing session backup extension artifact");
  const expected = `// Generated by bun run backups:build. Do not edit.\n${await artifact.text()}`;
  if (process.argv.includes("--check")) {
    if (
      (await Bun.file(output)
        .text()
        .catch(() => "")) !== expected
    )
      throw new Error("Session backup bundle is stale; run bun run backups:build");
  } else await Bun.write(output, expected);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
